def canonical(name):
    cleaned = " ".join(name.split())
    key = normalized(cleaned)
    if key in KNOWN:
        return KNOWN[key]
    if any(key.startswith(prefix + " ") or key == prefix for prefix in PORTUGUESE_STARTS):
        # Ajustar grafia clara de equipamentos e títulos para pt-BR.
        return cleaned.replace("(Maquina)", "(Máquina)").replace("(Halteres)", "(Halter)")
    return ""  # TODO(metodologia): validar nomes sem correspondência inequívoca
